/**
 * GrantMatch — AI Recommendation Route
 * =======================================
 * POST /api/recommendations
 *
 * Generates AI-assisted scholarship recommendations for the authenticated student.
 * Workflow:
 *   1. Load the student's full profile from the authenticated session (req.user).
 *   2. Fetch all Published, non-expired opportunities from MongoDB.
 *   3. Run the deterministic eligibility engine (matcher.js) on each opportunity.
 *   4. Classify each as: eligible | partial | ineligible.
 *   5. Optionally call the Python FastAPI AI service to re-rank eligible results.
 *   6. Return enriched recommendations with explanations, gaps, and status.
 *
 * Design decisions:
 *   - The ML service is OPTIONAL. If unavailable, deterministic results are returned.
 *   - No sensitive fields beyond those needed for matching are sent to the AI service.
 *   - AI service URL is loaded from environment variable AI_SERVICE_URL.
 *   - Request timeout: 5 seconds to the AI service.
 */

const express = require('express');
const router  = express.Router();
const Opportunity = require('../models/Opportunity');
const { requireAuth } = require('../middleware/auth');
const { calculateMatch } = require('../utils/matcher');

const AI_SERVICE_URL = process.env.AI_SERVICE_URL || 'http://localhost:8000';
const AI_TIMEOUT_MS  = 5000;

const RECOMMENDATION_DISCLAIMER =
  'GrantMatch AI recommendations are generated by a deterministic eligibility engine ' +
  'assisted by an experimental Decision Tree model trained on synthetic data. ' +
  'Eligibility and award information must be verified on the official scholarship provider website. ' +
  'GrantMatch does not award scholarships or guarantee selection.';

// ---------------------------------------------------------------------------
// Helper: call the Python AI service for ML-based re-ranking
// ---------------------------------------------------------------------------
async function callAIRanking(studentProfile, eligibleOpps) {
  try {
    const controller = new AbortController();
    const timer = setTimeout(() => controller.abort(), AI_TIMEOUT_MS);

    // Only send non-sensitive profile fields needed for ranking
    const safeProfile = {
      educationLevel: studentProfile.educationLevel  || '',
      category:       studentProfile.category        || 'General',
      gender:         studentProfile.gender          || 'Any',
      fundingPurpose: studentProfile.fundingPurpose  || 'Education',
      percentage:     studentProfile.percentage      ?? null,
      age:            studentProfile.age             ?? null,
      annualIncome:   studentProfile.annualIncome    ?? null,
    };

    const payload = {
      student:      safeProfile,
      scholarships: eligibleOpps.map((opp, idx) => ({
        _id:                 String(opp._id),
        name:                opp.name,
        sch_id:              idx,
        genderEligibility:   opp.genderEligibility   || 'Any',
        educationLevels:     opp.educationLevels      || ['Any'],
        categoryEligibility: opp.categoryEligibility  || ['Any'],
        minimumPercentage:   opp.minimumPercentage    || 0,
        minAge:              opp.minAge               || 0,
        maxAge:              opp.maxAge               || 100,
        incomeLimit:         opp.incomeLimit          || 0,
      })),
    };

    const res = await fetch(`${AI_SERVICE_URL}/rank`, {
      method:  'POST',
      headers: { 'Content-Type': 'application/json' },
      body:    JSON.stringify(payload),
      signal:  controller.signal,
    });

    clearTimeout(timer);

    if (!res.ok) {
      console.warn(`[AI Service] Returned HTTP ${res.status} — falling back to deterministic order.`);
      return null;
    }

    const json = await res.json();
    return json;  // { ranked: [...], model_meta: {...}, disclaimer: "..." }
  } catch (err) {
    if (err.name === 'AbortError') {
      console.warn('[AI Service] Request timed out — falling back to deterministic order.');
    } else {
      console.warn('[AI Service] Unavailable:', err.message, '— falling back to deterministic order.');
    }
    return null;
  }
}

// ---------------------------------------------------------------------------
// POST /api/recommendations
// @desc  Return AI-enriched scholarship recommendations for authenticated user
// @access Private (requireAuth)
// ---------------------------------------------------------------------------
router.post('/', requireAuth, async (req, res) => {
  try {
    const user = req.user;  // Loaded from JWT by requireAuth middleware
    const now  = new Date();

    // 1. Fetch all Published opportunities that have not expired
    const opportunities = await Opportunity.find({
      status:   'Published',
      deadline: { $gte: now },
    }).lean();

    if (opportunities.length === 0) {
      return res.json({
        success:    true,
        total:      0,
        disclaimer: RECOMMENDATION_DISCLAIMER,
        recommendations: [],
        aiAssisted: false,
        message:    'No active scholarship opportunities found at this time.',
      });
    }

    // 2. Run deterministic eligibility engine on every opportunity
    const evaluated = opportunities.map((opp) => {
      const matchResult = calculateMatch(user, opp);
      const daysRemaining = Math.ceil((new Date(opp.deadline) - now) / (1000 * 60 * 60 * 24));

      // Determine eligibility tier
      let eligibilityStatus;
      if (matchResult.matchPercentage >= 75 && matchResult.gaps.length === 0) {
        eligibilityStatus = 'eligible';
      } else if (matchResult.matchPercentage >= 40) {
        eligibilityStatus = 'partial';
      } else {
        eligibilityStatus = 'ineligible';
      }

      // Build human-readable match explanation
      const matchExplanation = matchResult.reasons.length > 0
        ? matchResult.reasons.slice(0, 3).join('; ')
        : 'Profile evaluated against scholarship criteria.';

      return {
        _id:           opp._id,
        name:          opp.name,
        provider:      opp.provider,
        type:          opp.type,
        description:   opp.description,
        fundingAmount: opp.fundingAmount,
        fundingType:   opp.fundingType,
        deadline:      opp.deadline,
        officialUrl:   opp.officialUrl,
        country:       opp.country,
        state:         opp.state,
        requiredDocuments: opp.requiredDocuments || [],
        daysRemaining,
        eligibilityStatus,
        eligibilityMatch:  matchResult.matchPercentage,
        matchExplanation,
        matchReasons:  matchResult.reasons,
        gaps:          matchResult.gaps,
        breakdown:     matchResult.breakdown,
        // ML fields filled in after optional AI ranking step
        ml_rank_score: null,
        aiRanked:      false,
      };
    });

    // 3. Separate eligible/partial for AI re-ranking; always include ineligible last
    const eligible   = evaluated.filter(o => o.eligibilityStatus === 'eligible');
    const partial    = evaluated.filter(o => o.eligibilityStatus === 'partial');
    const ineligible = evaluated.filter(o => o.eligibilityStatus === 'ineligible');

    // Sort each tier by deterministic match score as fallback
    const sortByMatch = (a, b) => b.eligibilityMatch - a.eligibilityMatch;
    eligible.sort(sortByMatch);
    partial.sort(sortByMatch);
    ineligible.sort(sortByMatch);

    // 4. Attempt ML re-ranking of top opportunities
    let aiAssisted    = false;
    let aiModelMeta   = null;
    const toRank      = [...eligible, ...partial.slice(0, 5)];

    if (toRank.length > 0) {
      const aiResponse = await callAIRanking(user, toRank);

      if (aiResponse && Array.isArray(aiResponse.ranked)) {
        // Build a lookup of ML scores by opportunity _id
        const mlScoreMap = {};
        aiResponse.ranked.forEach((r) => {
          if (r._id) mlScoreMap[String(r._id)] = r.ml_rank_score ?? 0;
        });

        // Apply ML rank scores back to evaluated items
        toRank.forEach((opp) => {
          const score = mlScoreMap[String(opp._id)];
          if (score !== undefined) {
            opp.ml_rank_score = score;
            opp.aiRanked      = true;
          }
        });

        // Re-sort using ML score (primary) then deterministic match (secondary)
        toRank.sort((a, b) => {
          const mlDiff = (b.ml_rank_score ?? 0) - (a.ml_rank_score ?? 0);
          return mlDiff !== 0 ? mlDiff : b.eligibilityMatch - a.eligibilityMatch;
        });

        aiAssisted  = true;
        aiModelMeta = aiResponse.model_meta || null;
      }
    }

    // 5. Build final ordered recommendations list
    const recommendations = [
      ...toRank,
      ...ineligible,
    ];

    // Identify profile completeness gaps (fields used in matching)
    const profileGaps = [];
    if (!user.percentage && user.percentage !== 0) profileGaps.push('Academic percentage not set in profile');
    if (!user.annualIncome && user.annualIncome !== 0) profileGaps.push('Annual family income not set');
    if (!user.educationLevel) profileGaps.push('Education level not specified');
    if (!user.state) profileGaps.push('Home state not specified');
    if (!user.age) profileGaps.push('Age not specified');

    return res.json({
      success:    true,
      total:      recommendations.length,
      eligible:   eligible.length,
      partial:    partial.length,
      ineligible: ineligible.length,
      aiAssisted,
      aiModelMeta,
      profileGaps,
      disclaimer: RECOMMENDATION_DISCLAIMER,
      recommendations,
    });

  } catch (err) {
    console.error('[Recommendations] Error:', err);
    return res.status(500).json({
      success: false,
      message: 'Failed to generate recommendations. Please try again.',
      error:   process.env.NODE_ENV === 'development' ? err.message : undefined,
    });
  }
});

module.exports = router;
